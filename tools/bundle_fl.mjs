// Bundle the factory-line model library (../factory-line/src: the SMT line machines, the plant machines, the
// shared builder kit and the lab / heavy / general builders, plus the text → kind rules) into fl-models.js, a
// classic script for the three.js r128 build the hall pages use. hall-kit.js stands these models in the halls.
//   node tools/bundle_fl.mjs [path/to/factory-line/src]
import {readFileSync, writeFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] || join(root, '..', 'factory-line', 'src');
const read = f => readFileSync(join(src, f), 'utf8');
const strip = s => s.replace(/^import .*;$/mg, '').replace(/^export (const|function|let)/mg, '$1');
const builders = f => [...read(f).matchAll(/^export function (build\w+)/mg)].map(m => m[1]);
const wrap = f => {const names = builders(f); return `(function(){\n${strip(read(f))}\nObject.assign(B,{${names.map(n => `${n[5].toLowerCase() + n.slice(6)}:${n}`).join(',')}});\n})();\n`};
const rules = read('maynards.js').match(/^export const KIND_RULES=\[[\s\S]*?^\];/m)[0].replace('export ', '');
const out = `// Generated by tools/bundle_fl.mjs from the factory-line project (src/factoryModels.js, plantModels.js, steelModels/kit.js,
// maynardsModels/lab.js, heavy.js, general.js and the KIND_RULES of maynards.js). Do not edit by hand.
// window.FL = {createLineModels, createPlantModels, createKit, builders, KIND_RULES, kindOf, LINE_LAYOUT, MACHINE_SIZE}
(function(){
'use strict';
if(!THREE.SRGBColorSpace){THREE.SRGBColorSpace='srgb';THREE.LinearSRGBColorSpace='srgb-linear';
 Object.defineProperty(THREE.Texture.prototype,'colorSpace',{get(){return this.encoding===THREE.sRGBEncoding?'srgb':'srgb-linear'},set(v){this.encoding=v==='srgb'?THREE.sRGBEncoding:THREE.LinearEncoding;this.needsUpdate=true},configurable:true})}
${strip(read('factoryModels.js'))}
${strip(read('plantModels.js'))}
${strip(read('steelModels/kit.js'))}
const B={};
${wrap('maynardsModels/lab.js')}${wrap('maynardsModels/heavy.js')}${wrap('maynardsModels/general.js')}
${rules}
const kindOf=text=>{for(const [re,k] of KIND_RULES)if(re.test(text))return k;return null};
window.FL={createLineModels,createPlantModels,createKit,builders:B,KIND_RULES,kindOf,LINE_LAYOUT,MACHINE_SIZE};
})();
`;
writeFileSync(join(root, 'fl-models.js'), out);
console.log('fl-models.js:', out.length, 'bytes, builders:', Object.keys(B_names()).length);
function B_names(){const o = {}; for (const f of ['maynardsModels/lab.js', 'maynardsModels/heavy.js', 'maynardsModels/general.js']) for (const n of builders(f)) o[n] = 1; return o}
