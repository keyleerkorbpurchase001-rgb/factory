#!/usr/bin/env python3
"""Write hall-data.js from the portal's embedded data (index.html, const D): for every hall its name, lines and
stations (line, step, station, status, lot, machine, year, serial, key specs, size / weight, note), and the halls of
each plant in order. The hall pages read it (hall-kit.js) for their station chips, machine details and hall list."""
import json, re, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(root, 'index.html'), encoding='utf-8').read()
m = re.search(r'\nconst D=(\{.*?\});\n', s, re.S)
D = json.loads(m.group(1))
halls = {}
for k, h in D['halls'].items():
    halls[k] = {'name': h['name'], 'short': h.get('short', ''), 'lines': [{'name': l['name'], 'sub': l.get('sub', '')} for l in h['lines']], 'top': h.get('top'), 'rows': []}
for i, r in enumerate(D['rows']):
    halls[r['hall']]['rows'].append({'_i': i, 'line': r.get('line') or 0, 'step': r.get('step') or 0, 'station': r['station'], 'kind': r['kind'], 'lot': r.get('lot', ''), 'name': r.get('name', ''),
                                      'year': r.get('year', ''), 'serial': r.get('serial', ''), 'supply': r.get('supply', ''), 'weight': r.get('weight', ''), 'note': r.get('note', ''), 'ph': (r.get('ph') or [''])[0]})
facs = [{'key': f['key'], 'name': f['name'], 'short_name': f.get('short_name', f['name']), 'halls': f['halls']} for f in D['factories']]
out = '// Generated by tools/make_hall_data.py from index.html: every hall with its lines and stations. Do not edit by hand.\nwindow.HALL_DATA=' + json.dumps({'halls': halls, 'factories': facs}, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(root, 'hall-data.js'), 'w', encoding='utf-8').write(out)
print('hall-data.js:', len(out), 'bytes,', sum(len(h['rows']) for h in halls.values()), 'rows,', len(halls), 'halls')
